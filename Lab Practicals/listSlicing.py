# Program for slicing operations

list = [10, 20, 30, 40, 50, 60, 70]
print("Original List:", list)

print("Slice from beginning to index 3:", list[:3])
print("Slice from index 3 to end:", list[3:])
print("Negative index slicing (last 3 elements):", list[-3:])
print("Reverse list using slicing:", list[::-1])
